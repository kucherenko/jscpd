//! A standalone HTML page for a dead-code run.
//!
//! Self-contained on purpose: one file with its styles inlined, so it can be
//! opened from a CI artifact, attached to a review, or served from anywhere
//! without a second request.

use super::structured::escape_xml;
use super::{DeadCodeContext, DeadCodeReporter, group_by_category, location, reasons_clause};
use crate::reporter::{ReporterError, ReporterOptions};
use crate::shared::{Style, write_report_file};
use cpd_core::deadcode::{ConfidenceLevel, Finding};
use std::fmt::Write;
use std::path::Path;

pub struct HtmlReporter {
    style: Style,
    tool_version: String,
}

impl HtmlReporter {
    pub fn new(options: &ReporterOptions) -> Self {
        Self {
            style: Style::new(options.no_colors),
            tool_version: options.tool_version.clone(),
        }
    }
}

impl DeadCodeReporter for HtmlReporter {
    fn name(&self) -> &str {
        "html"
    }

    fn report(
        &self,
        findings: &[Finding],
        ctx: &DeadCodeContext<'_>,
        output_dir: &Path,
    ) -> Result<(), ReporterError> {
        let stats = ctx.stats;
        let mut body = String::new();

        let _ = write!(
            body,
            r#"<header><h1>Dead code</h1><p class="sub">{files} files · {symbols} declarations · {entries} entry points · {date}</p></header>
<section class="cards">
  {cards}
</section>"#,
            files = stats.files,
            symbols = stats.symbols,
            entries = stats.entry_points,
            date = escape_xml(&stats.detection_date),
            cards = cards(findings, stats),
        );

        if findings.is_empty() {
            body.push_str("<section class=\"empty\"><p>No dead code found.</p></section>");
        }
        for (category, group) in group_by_category(findings) {
            let _ = write!(
                body,
                "<section><h2>{} <span class=\"count\">{}</span></h2><table><thead><tr><th>Location</th><th>Name</th><th>Lines</th><th>Confidence</th><th>Why not certain</th></tr></thead><tbody>",
                escape_xml(category.title()),
                group.len()
            );
            for finding in group {
                let reasons = reasons_clause(finding);
                let _ = write!(
                    body,
                    "<tr><td class=\"loc\">{}</td><td class=\"name\">{}</td><td class=\"num\">{}</td><td><span class=\"badge {}\">{}%</span></td><td class=\"why\">{}</td></tr>",
                    escape_xml(&location(finding)),
                    escape_xml(&display_name(finding)),
                    finding.lines,
                    level_class(finding.level()),
                    finding.confidence,
                    escape_xml(&reasons),
                );
            }
            body.push_str("</tbody></table></section>");
        }

        let html = format!(
            "<!doctype html>\n<html lang=\"en\"><head><meta charset=\"utf-8\"><meta name=\"viewport\" content=\"width=device-width, initial-scale=1\"><title>Dead code report</title><style>{CSS}</style></head><body><main>{body}<footer>Generated by basta {version}</footer></main></body></html>\n",
            version = escape_xml(&self.tool_version),
        );
        write_report_file(
            output_dir,
            "basta-report.html",
            html,
            &self.style,
            "Dead code HTML",
        )?;
        Ok(())
    }
}

fn cards(findings: &[Finding], stats: &cpd_core::deadcode::Stats) -> String {
    let mut out = String::new();
    let card = |label: &str, value: String, tone: &str| {
        format!(
            "<div class=\"card {tone}\"><div class=\"value\">{value}</div><div class=\"label\">{label}</div></div>"
        )
    };
    out.push_str(&card(
        "findings",
        findings.len().to_string(),
        if findings.is_empty() { "good" } else { "warn" },
    ));
    out.push_str(&card("dead lines", stats.dead_lines.to_string(), "plain"));
    out.push_str(&card(
        "of codebase",
        format!("{:.1}%", stats.percentage),
        "plain",
    ));
    out.push_str(&card(
        "unreached files",
        stats
            .files
            .saturating_sub(stats.reachable_files)
            .to_string(),
        "plain",
    ));
    out
}

fn display_name(finding: &Finding) -> String {
    match (&finding.parent, &finding.exported_as) {
        _ if finding.name.is_empty() => "—".to_string(),
        (Some(parent), _) => format!("{parent}.{}", finding.name),
        (None, Some(exported)) => format!("{} → {exported}", finding.name),
        (None, None) => finding.name.clone(),
    }
}

fn level_class(level: ConfidenceLevel) -> &'static str {
    match level {
        ConfidenceLevel::Certain => "certain",
        ConfidenceLevel::High => "high",
        ConfidenceLevel::Medium => "medium",
        ConfidenceLevel::Low => "low",
    }
}

