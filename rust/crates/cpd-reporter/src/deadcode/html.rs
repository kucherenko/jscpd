#[cfg(test)]
mod tests {
    use super::super::fixtures;
    use super::*;
    use cpd_core::deadcode::{Category, Stats};
    use std::path::PathBuf;
    use std::time::Duration;

    fn render(findings: &[Finding], stats: &Stats) -> String {
        let dir = fixtures::unique_dir("html");
        let options = ReporterOptions::new(PathBuf::from("/tmp"));
        let ctx = DeadCodeContext::new(stats, Duration::ZERO);
        HtmlReporter::new(&options)
            .report(findings, &ctx, &dir)
            .unwrap();
        let html = std::fs::read_to_string(dir.join("basta-report.html")).unwrap();
        std::fs::remove_dir_all(&dir).ok();
        html
    }

    #[test]
    fn the_page_is_a_complete_self_contained_document() {
        let stats = fixtures::stats();
        let html = render(&fixtures::findings(), &stats);
        assert!(html.starts_with("<!doctype html>"));
        assert!(html.trim_end().ends_with("</html>"));
        assert!(html.contains("<style>"), "styles are inlined, not linked");
        assert!(
            !html.contains("<link ") && !html.contains("<script"),
            "the report must open from a CI artifact with no network"
        );
        assert_eq!(
            html.matches("<table>").count(),
            html.matches("</table>").count()
        );
    }

    #[test]
    fn every_category_present_gets_a_section() {
        let stats = fixtures::stats();
        let html = render(&fixtures::findings(), &stats);
        for title in ["Unused files", "Unused exports", "Unused imports"] {
            assert!(html.contains(title), "{title} missing");
        }
        assert!(
            !html.contains("Unused members"),
            "empty categories are omitted"
        );
    }

    #[test]
    fn a_clean_run_renders_the_empty_state() {
        let stats = Stats::default();
        let html = render(&[], &stats);
        assert!(html.contains("No dead code found."));
        assert!(html.contains("class=\"card good\""), "{html}");
    }

    #[test]
    fn user_content_is_escaped_rather_than_injected() {
        let mut finding = fixtures::finding(
            Category::UnusedExport,
            "src/<script>alert(1)</script>.ts",
            "a&b",
            85,
        );
        finding.message = "<img onerror=x>".into();
        let stats = fixtures::stats();
        let html = render(&[finding], &stats);
        assert!(!html.contains("<script>alert"), "{html}");
        assert!(
            html.contains("&lt;script&gt;alert(1)&lt;/script&gt;"),
            "{html}"
        );
        assert!(html.contains("a&amp;b"), "{html}");
    }

    #[test]
    fn the_page_defines_both_colour_schemes() {
        let stats = Stats::default();
        let html = render(&[], &stats);
        assert!(html.contains("color-scheme:light dark"));
        assert!(html.contains("prefers-color-scheme:dark"));
    }

    #[test]
    fn a_file_finding_shows_a_dash_rather_than_an_empty_name() {
        let finding = fixtures::finding(Category::UnusedFile, "src/a.ts", "", 95);
        assert_eq!(display_name(&finding), "—");
    }
}
